/** Deterministically places `correct` among 3 distractors based on `seed`, so
 *  the correct option isn't always first — without using Math.random(),
 *  which would make QUESTION_BANK differ between server and client renders
 *  (a hydration bug). Same seed always produces the same layout. */
function deterministicOptions<T>(correct: T, distractors: [T, T, T], seed: number): T[] {
  const pos = ((seed % 4) + 4) % 4;
  const options: T[] = [];
  let d = 0;
  for (let i = 0; i < 4; i++) {
    options.push(i === pos ? correct : distractors[d++]);
  }
  return options;
}

/** Deterministic (non-random) shuffle for puzzle word order — same small
 *  seeded PRNG used elsewhere in the codebase for reproducible variety. */
function seededShuffleWords(words: string[], seed: number): string[] {
  const copy = [...words];
  let s = seed;
  for (let i = copy.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280;
    const j = Math.floor((s / 233280) * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/** Generic, part-of-speech-safe carrier sentences for the puzzle variant
 *  below — every theme's vocabulary is an article+noun phrase (e.g. "la
 *  actividad física"), so slotting it into any of these frames always
 *  produces a grammatically valid sentence, rotated by word index for
 *  variety. */
const PUZZLE_FRAMES: ((es: string) => string)[] = [
  (es) => `${es} es muy importante en mi vida diaria`,
  (es) => `todos deberíamos aprender más sobre ${es}`,
  (es) => `en mi opinión ${es} es un tema muy interesante`,
  (es) => `mis padres siempre hablan sobre ${es} en casa`,
];

/** Turns one theme's vocabulary list into 9 question variants per word:
 *  recognize the meaning (mcq, both directions), produce it from memory
 *  (typed, both directions), recognize it by ear (listening — the word is
 *  spoken aloud via the Web Speech API, no text shown), reading-context/
 *  writing-register/synonym drills, and — the one exam format previously
 *  missing from the auto-generated pool — a sentence-ordering puzzle. This
 *  is what gets every theme comfortably past 1,000 questions while staying
 *  grammatically safe — no free-form sentence generation, just
 *  translation/listening/word-order drills built from fixed, POS-safe
 *  frames, which is exactly how vocabulary range is tested on the real
 *  exam. */
function buildVocabQuestions(theme: Theme): QuizItem[] {
  const vocab = theme.vocabulary;
  const n = vocab.length;
  const items: QuizItem[] = [];

  vocab.forEach((v, i) => {
    const d1 = vocab[(i + 1) % n];
    const d2 = vocab[(i + 2) % n];
    const d3 = vocab[(i + 3) % n];

    items.push({
      id: `${theme.id}-v${i}-mcq-en`,
      themeId: theme.id,
      type: "mcq",
      prompt: `¿Qué significa '${v.es}'?`,
      options: deterministicOptions(v.en, [d1.en, d2.en, d3.en], i),
      correctAnswer: v.en,
      difficulty: "easy",
      points: 10,
      explanation: `'${v.es}' significa '${v.en}' en inglés. (Vocabulario de ${v.subtopic}.)`,
    });

    items.push({
      id: `${theme.id}-v${i}-mcq-es`,
      themeId: theme.id,
      type: "mcq",
      prompt: `¿Cuál palabra en español significa '${v.en}'?`,
      options: deterministicOptions(v.es, [d1.es, d2.es, d3.es], i + 2),
      correctAnswer: v.es,
      difficulty: "medium",
      points: 20,
      explanation: `'${v.en}' se traduce como '${v.es}' en español. (Vocabulario de ${v.subtopic}.)`,
    });

    items.push({
      id: `${theme.id}-v${i}-type-es`,
      themeId: theme.id,
      type: "short",
      prompt: `Traduce al español: '${v.en}'`,
      correctAnswer: v.es,
      difficulty: "medium",
      points: 20,
      explanation: `'${v.en}' se traduce como '${v.es}' en español. (Vocabulario de ${v.subtopic}.)`,
    });

    items.push({
      id: `${theme.id}-v${i}-type-en`,
      themeId: theme.id,
      type: "short",
      prompt: `Traduce al inglés: '${v.es}'`,
      correctAnswer: v.en,
      difficulty: "easy",
      points: 10,
      explanation: `'${v.es}' significa '${v.en}' en inglés. (Vocabulario de ${v.subtopic}.)`,
    });

    // 5. Audio Listening drill (Spoken Spanish -> English MCQ)
    items.push({
      id: `${theme.id}-v${i}-listen-en`,
      themeId: theme.id,
      type: "listening",
      prompt: `[Escuchar - ${v.subtopic}] Escucha atentamente la palabra en español y selecciona el significado exacto en inglés:`,
      audioText: v.es,
      options: deterministicOptions(v.en, [d1.en, d2.en, d3.en], i + 1),
      correctAnswer: v.en,
      difficulty: "medium",
      points: 20,
      explanation: `Spanish audio: "${v.es}" translates to "${v.en}" in English.`,
    });

    // 6. IB Paper 1 / Reading Comprehension Context Fill-in-the-blank (Spanish context)
    items.push({
      id: `${theme.id}-v${i}-ib-context`,
      themeId: theme.id,
      type: "short",
      prompt: `[Comprensión de lectura - ${v.subtopic}] Completa la oración con la palabra adecuada: "En el contexto de ${v.subtopic.toLowerCase()}, ___ (${v.en}) es fundamental para el desarrollo."`,
      correctAnswer: v.es,
      difficulty: "medium",
      points: 25,
      explanation: `La palabra adecuada en español es "${v.es}".`,
    });

    // 7. IB Paper 2 / Writing Register & Format Question
    items.push({
      id: `${theme.id}-v${i}-ib-format`,
      themeId: theme.id,
      type: "mcq",
      prompt: `[Redacción IB - ${v.subtopic}] Si estás escribiendo sobre "${v.es}" (${v.en}), ¿cuál es el término clave más adecuado en español?`,
      options: deterministicOptions(v.es, [d1.es, d2.es, d3.es], i + 3),
      correctAnswer: v.es,
      difficulty: "easy",
      points: 15,
      explanation: `"${v.es}" es el término técnico clave para la subtemática ${v.subtopic}.`,
    });

    // 8. IB Synonym & Vocabulary Matching MCQ
    items.push({
      id: `${theme.id}-v${i}-ib-synonym`,
      themeId: theme.id,
      type: "mcq",
      prompt: `[Vocabulario de examen] Selecciona el equivalente exacto para la expresión inglesa "${v.en}":`,
      options: deterministicOptions(v.es, [d1.es, d2.es, d3.es], i + 4),
      correctAnswer: v.es,
      difficulty: "medium",
      points: 20,
      explanation: `En español estándar de IB, "${v.en}" se traduce como "${v.es}".`,
    });

    // 9. Sentence-ordering puzzle — the exam format most underrepresented in
    // the auto-generated pool (previously 0 puzzle items came from vocab;
    // all 42 puzzle questions in the whole bank were hand-written).
    const sentence = PUZZLE_FRAMES[i % PUZZLE_FRAMES.length](v.es);
    items.push({
      id: `${theme.id}-v${i}-puzzle`,
      themeId: theme.id,
      type: "puzzle",
      prompt: `[Ordenar - ${v.subtopic}] Ordena las palabras para formar una oración correcta:`,
      options: seededShuffleWords(sentence.split(" "), i + 5),
      correctAnswer: sentence,
      difficulty: "medium",
      points: 25,
      explanation: `Oración correcta: "${sentence}".`,
    });

    // 10. True/false meaning-check — mirrors the IB Paper 1 true/false
    // format (QuizItemType has no dedicated "true-false" type, so it's
    // answered as typed "verdadero"/"falso", same convention used for
    // true/false answers elsewhere in the app). Capped to the first 20
    // words per theme (100 total) rather than every word, so this rounds
    // the bank out to ~1,000 net-new questions instead of another 850.
    if (i < 20) {
      const isTrueClaim = i % 2 === 0;
      const claimedMeaning = isTrueClaim ? v.en : vocab[(i + 4) % n].en;
      items.push({
        id: `${theme.id}-v${i}-truefalse`,
        themeId: theme.id,
        type: "short",
        prompt: `Verdadero o falso — responde "verdadero" o "falso": '${v.es}' significa '${claimedMeaning}' en inglés.`,
        correctAnswer: isTrueClaim ? "verdadero" : "falso",
        difficulty: "easy",
        points: 10,
        explanation: `'${v.es}' significa '${v.en}' en inglés.`,
      });
    }
  });

  return items;
}

